"""Reviewable selection and immutable confirmation preregistration.

Selection reads model42 tuning ONLY. Old models43/44 remain a fixed model set;
fresh search seeds do not become fresh independent trainings.
"""
from __future__ import annotations

from collections import defaultdict
from copy import deepcopy
from datetime import datetime, timezone
import json
from pathlib import Path

import numpy as np

from research_experiments.common.metrics import pareto_mask
from .storage import (ROOT, RESULTS, output_path, file_hash, fingerprint, source_identity,
                      runtime_identity, write_json, input_path)
from .analysis import load_rows
from .config import required_inputs, treatment


GUARDS = dict(max_entropy_drop=.2, min_pairwise_rms_ratio=.8,
              max_near_duplicate_increase=.05, max_train_extreme_close_increase=.05)


def propose_selection(pilot_root, destination=None):
    rows = [r for r in load_rows(pilot_root) if r["study"] == "mnist_tuning" and r["phase"] == "pilot_tune"
            and r["model_seed"] == 42 and r["output_policy"] == "native" and r["ranking_eligible"]]
    by_label = defaultdict(list)
    source_digest = source_identity()["digest"]
    if any(r.get("source_digest") != source_digest for r in rows):
        raise ValueError("Tuning evidence was generated by different source bytes; keep one frozen source cohort")
    for r in rows:
        by_label[r["label"]].append(r)
    candidates, baseline = [], by_label.get("DDIM105", [])
    if len(baseline) != 5 or {r["search_seed"] for r in baseline} != set(range(5)):
        raise ValueError("Selection requires all five eligible model42 DDIM105 tuning seeds")
    means = lambda runs, key: float(np.mean([r[key] for r in runs]))
    baseline_means = {k: means(baseline, k) for k in ["class_entropy", "pairwise_rms", "near_duplicate_fraction",
                                                    "pixel_train_extreme_close_fraction", "feature_train_extreme_close_fraction"]}
    for label, runs in sorted(by_label.items()):
        if len(runs) != 5 or {r["search_seed"] for r in runs} != set(range(5)) or len({r["treatment"] for r in runs}) != 1:
            continue
        if label.startswith("DDIM"):
            continue
        family = "single" if label.startswith("single") else label.split("_")[0]
        avg = {k: means(runs, k) for k in ["pixel_knn", "feature_knn", *baseline_means]}
        failures = []
        if avg["class_entropy"] < baseline_means["class_entropy"] - GUARDS["max_entropy_drop"]:
            failures.append("class entropy guard")
        if avg["pairwise_rms"] < baseline_means["pairwise_rms"] * GUARDS["min_pairwise_rms_ratio"]:
            failures.append("pairwise diversity guard")
        if avg["near_duplicate_fraction"] > baseline_means["near_duplicate_fraction"] + GUARDS["max_near_duplicate_increase"]:
            failures.append("near-duplicate guard")
        for name in ["pixel", "feature"]:
            key = name + "_train_extreme_close_fraction"
            if avg[key] > baseline_means[key] + GUARDS["max_train_extreme_close_increase"]:
                failures.append(name + " train proximity guard")
        candidates.append(dict(label=label, family=family, treatment=runs[0]["treatment"], means=avg,
                               guard_failures=failures, eligible_for_selection=not failures,
                               n_search_seeds=5, source_model=42))
    for family in {c["family"] for c in candidates}:
        eligible = [c for c in candidates if c["family"] == family and c["eligible_for_selection"]]
        mask = pareto_mask([[c["means"][k] for k in ["pixel_knn", "feature_knn"]] for c in eligible], [True, True]) if eligible else []
        for c, keep in zip(eligible, mask):
            c["support_frontier"] = bool(keep)
    draft = dict(format="dms_v2_selection", reviewed=False, review_notes="",
                 pilot_root=str(output_path(pilot_root)), pilot_model42_only=True,
                 source_digest=source_digest, guards=GUARDS,
                 rule="Select at most 8 MNIST treatments, including controls; support Pareto within mechanism family under predeclared diversity/proximity guards. Resolve remaining tradeoffs explicitly before lock.",
                 chosen_labels=dict(exact=["M1_ddim", "M2_single", "M3_multi", "M4_merge", "M6_split_v2", "M7_extra_starts", "M8_merge_restarts"],
                                    mnist=["DDIM105", "DDIM50_matched_pool", "multi_l2_003"]),
                 candidates=candidates,
                 mnist_roles=dict(optimized_single=None),
                 hypotheses=[dict(id="H_merge", claim="Merge saves queries under a cap while preserving recall within 0.05",
                                  clauses=[dict(study="confirmation_exact_cap", contrast="merge_cap_savings", metric="queries", direction="less", threshold=0.),
                                           dict(study="confirmation_exact_cap", contrast="merge_cap_savings", metric="one_to_one_recall", direction="greater", threshold=-.05)]),
                             dict(id="H_split", claim="Split improves rare-mode recall over extra independent starts at matched queries",
                                  clauses=[dict(study="confirmation_exact", contrast="split_vs_extra", metric="rare_recall", direction="greater", threshold=0., filters=dict(family=["rare"]))]),
                             dict(id="H_mnist", claim="Current multi-level improves BOTH support distances over the selected optimized single-level; diversity/proximity guards are assessed separately",
                                  required_guard_labels=["multi_l2_003"],
                                  clauses=[dict(study="confirmation_mnist", contrast="SELECTED_SINGLE_VS_CURRENT", metric=k, direction="greater", threshold=0.) for k in ["pixel_knn", "feature_knn"]])],
                 manual_overrides={}, confirmation_scope="new search seeds on fixed existing MNIST models43/44; fresh synthetic distributions")
    if destination is not None:
        write_json(destination, draft)
    return draft


def filter_selected(groups, selection):
    chosen = selection.get("chosen_labels", {})
    if any(len(labels) != len(set(labels)) for labels in chosen.values()):
        raise ValueError("Selected labels must be unique")
    if not selection.get("reviewed") or not selection.get("review_notes") or not selection.get("hypotheses"):
        raise ValueError("Selection/hypotheses must be reviewed with explicit notes before lock")
    if not {"M1_ddim", "M2_single", "M3_multi", "M4_merge", "M7_extra_starts"} <= set(chosen.get("exact", [])):
        raise ValueError("Synthetic confirmation must retain sampling, single/multi independent, Merge and extra-start controls")
    if not {"DDIM105", "DDIM50_matched_pool", "multi_l2_003"} <= set(chosen.get("mnist", [])):
        raise ValueError("MNIST confirmation must retain both DDIM controls and the fixed multi-level baseline")
    if not any(label.startswith("single") for label in chosen["mnist"]):
        raise ValueError("An optimized single-level comparator is mandatory")
    if not 4 <= len(chosen["mnist"]) <= 8 or not 4 <= len(chosen["exact"]) <= 8:
        raise ValueError("Use 4..8 selected treatments per domain, not the whole tuning grid")
    candidates = {c["label"]: c for c in selection.get("candidates", [])}
    fixed = {"DDIM105", "DDIM50_matched_pool", "multi_l2_003"}
    for label in chosen["mnist"]:
        if label in fixed:
            continue
        candidate = candidates.get(label)
        accepted = candidate and candidate.get("eligible_for_selection") and candidate.get("support_frontier")
        if not accepted and not selection.get("manual_overrides", {}).get(label):
            raise ValueError(f"{label} is not a model42 guarded frontier treatment; record a scientific reason for an explicit preregistered override")
    selected, available = [], defaultdict(set)
    for group in groups:
        jobs = []
        for job in group["jobs"]:
            c = job["config"]
            available[c["domain"]].add(job["label"])
            if job["label"] in chosen.get(c["domain"], []):
                if c["phase"] != "confirmation":
                    raise ValueError("Confirmation group contains a non-confirmation phase")
                jobs.append(job)
        labels = {j["label"] for j in jobs}
        contrasts = [s for s in group["contrasts"] if {s["left"], s["right"]} <= labels]
        if jobs:
            if not contrasts:
                raise ValueError("Selected confirmation has no predeclared contrasts")
            selected.append(dict(group, jobs=jobs, contrasts=contrasts))
    for domain, labels in chosen.items():
        if not set(labels) <= available[domain]:
            raise ValueError(f"Selected labels missing from blueprint: {domain}: {set(labels)-available[domain]}")
    return selected


def resolved_hypotheses(selection, groups):
    hypotheses = deepcopy(selection["hypotheses"])
    singles = [label for label in selection["chosen_labels"]["mnist"] if label.startswith("single")]
    role = selection.get("mnist_roles", {}).get("optimized_single") or (singles[0] if len(singles) == 1 else None)
    lookup = {(j["config"]["study"], c["id"]): c for g in groups for j in g["jobs"][:1] for c in g["contrasts"]}
    for hypothesis in hypotheses:
        if not hypothesis.get("id") or not hypothesis.get("claim") or not hypothesis.get("clauses"):
            raise ValueError("Hypotheses need an id, claim and operational clauses")
        for clause in hypothesis["clauses"]:
            if clause["contrast"] == "SELECTED_SINGLE_VS_CURRENT":
                if role not in singles:
                    raise ValueError("Set mnist_roles.optimized_single to one selected single-level treatment")
                candidates = [c for (study, _), c in lookup.items() if study == "confirmation_mnist"
                              and c["left"] == role and c["right"] == "multi_l2_003"]
                if len(candidates) != 1:
                    raise ValueError("No unique preregistered selected-single versus current-multi comparison")
                clause["contrast"] = candidates[0]["id"]
            spec = lookup.get((clause["study"], clause["contrast"]))
            if not spec or clause["metric"] not in spec.get("primary_metrics", []):
                raise ValueError("Hypothesis clause does not name a selected predeclared primary metric/contrast")
            if (clause.get("direction") not in {"less", "greater"} or type(clause.get("threshold")) not in {int, float}
                    or not np.isfinite(clause["threshold"])):
                raise ValueError("Predeclare a finite threshold and a direction")
    return hypotheses


def lock_confirmation(groups, pilot_groups, selection_path, destination, overrides=None):
    selection_path = output_path(selection_path)
    selection = json.loads(selection_path.read_text())
    if selection.get("format") != "dms_v2_selection":
        raise ValueError("A model42 selection document is required")
    recomputed = propose_selection(selection["pilot_root"])
    if selection.get("guards") != GUARDS or fingerprint(selection.get("candidates")) != fingerprint(recomputed["candidates"]):
        raise ValueError("Candidate evidence/guards differ from recomputed model42 tuning; edit choices and review notes only")
    selected = filter_selected(groups, selection)
    hypotheses = resolved_hypotheses(selection, selected)
    pilot = [j for g in pilot_groups for j in g["jobs"]]
    pilot_rows = load_rows(selection["pilot_root"])
    # Require completed selected tuning treatments, not a hand-typed list alone.
    signatures = {(r["label"], r["treatment"]) for r in pilot_rows if r["ranking_eligible"] and
                  (r["domain"] != "mnist" or r["study"] == "mnist_tuning" and r["model_seed"] == 42)}
    synth_seeds = {(j["config"]["problem"]["family"], j["config"]["problem"]["dim"], j["config"]["distribution_seed"])
                   for j in pilot if j["config"]["domain"] == "exact"}
    search_seeds = {j["config"]["seed"] for j in pilot}
    for g in selected:
        for j in g["jobs"]:
            c = j["config"]
            if (j["label"], treatment(c)) not in signatures:
                raise ValueError(f"Selected treatment has no eligible matching pilot evidence: {j['label']}")
            if c["seed"] in search_seeds:
                raise ValueError("Confirmation search seed overlaps pilot")
            if c["domain"] == "exact" and (c["problem"]["family"], c["problem"]["dim"], c["distribution_seed"]) in synth_seeds:
                raise ValueError("Confirmation distribution overlaps pilot")
    confirmation_root = output_path(RESULTS / "confirmation")
    if confirmation_root.exists() and any(confirmation_root.rglob("DONE.json")):
        raise ValueError("Confirmation outcomes already exist; do not create a new post-outcome preregistration")
    inputs = required_inputs([j for g in selected for j in g["jobs"]], overrides)
    missing = [p for p in inputs if not Path(p).is_file()]
    if missing:
        raise FileNotFoundError("Missing inputs before lock: " + ", ".join(missing))
    payload = dict(format="dms_v2_confirmation_lock", created_utc=datetime.now(timezone.utc).isoformat(),
                   selection=selection, selection_sha256=file_hash(selection_path),
                   source=source_identity(), runtime=runtime_identity(), overrides=overrides or {},
                   input_sha256={p: file_hash(p) for p in inputs}, groups=selected, hypotheses=hypotheses,
                   primary_rule="Bonferroni over the locked primary cells; exploratory strata are labelled; no outcome-adaptive changes",
                   model_inference_scope="conditional on the fixed pretrained MNIST models, not on unseen model trainings")
    payload["digest"] = fingerprint(payload)
    destination = output_path(destination)
    if destination.exists():
        raise FileExistsError("Lock is immutable; use a new named protocol before any confirmation outcomes")
    write_json(destination, payload, exclusive=True)
    return dict(path=str(destination), digest=payload["digest"], n_jobs=sum(len(g["jobs"]) for g in selected))


def validate_lock(path):
    p = output_path(path)
    lock = json.loads(p.read_text())
    expected = lock.pop("digest", None)
    if lock.get("format") != "dms_v2_confirmation_lock" or fingerprint(lock) != expected:
        raise ValueError("Corrupt or edited confirmation lock")
    if source_identity()["digest"] != lock["source"]["digest"]:
        raise ValueError("Code/config/dependency source changed after lock")
    if runtime_identity() != lock["runtime"]:
        raise ValueError("Runtime/dependency versions changed after lock")
    for name, sha in lock["input_sha256"].items():
        if not Path(name).is_file() or file_hash(name) != sha:
            raise ValueError(f"Locked input changed/missing: {name}")
    lock["digest"] = expected
    return lock
